// ── D: buildScheduledPreparationDiagnostic reason/stage whitelist ────────────
function freezePrep(overrides) {
  return Object.assign({ stage: 'plan-settings', reason: 'plan-settings-readback-mismatch' }, overrides || {});
}

test('D1 known reason codes are retained verbatim', () => {
  const p1 = rp.buildScheduledPreparationDiagnostic(freezePrep());
  assert.strictEqual(p1.reason, 'plan-settings-readback-mismatch');
  const p2 = rp.buildScheduledPreparationDiagnostic(freezePrep({ stage: 'account-binding', reason: 'account-drawer-footer-row-state-conflict' }));
  assert.strictEqual(p2.reason, 'account-drawer-footer-row-state-conflict');
});

test('D2 cookie-like reason string is sanitized, secret never crosses', () => {
  const packet = rp.buildScheduledPreparationDiagnostic(freezePrep({ reason: 'sessionid=FAKE_SECRET; passport=FAKE_TOKEN_ABC' }));
  assert.strictEqual(packet.reason, 'other-preparation-stop');
  const serialized = JSON.stringify(packet);
  assert.strictEqual(serialized.includes('FAKE_SECRET'), false);
  assert.strictEqual(serialized.includes('FAKE_TOKEN'), false);
});

test('D3 URL-with-token reason is sanitized regardless of length', () => {
  const packet = rp.buildScheduledPreparationDiagnostic(freezePrep({ reason: 'https://evil.example/x?token=FAKE' }));
  assert.strictEqual(packet.reason, 'other-preparation-stop');
  assert.strictEqual(JSON.stringify(packet).includes('evil.example'), false);
});

test('D4 96-char path-like reason is no longer copied', () => {
  const long = 'C:\\Users\\secret\\cookie-store-'.padEnd(96, 'x');
  const packet = rp.buildScheduledPreparationDiagnostic(freezePrep({ reason: long }));
  assert.strictEqual(packet.reason, 'other-preparation-stop');
  assert.strictEqual(JSON.stringify(packet).includes('secret'), false);
});

test('D5 non-string / empty reasons map to null', () => {
  assert.strictEqual(rp.buildScheduledPreparationDiagnostic(freezePrep({ reason: undefined })).reason, null);
  assert.strictEqual(rp.buildScheduledPreparationDiagnostic(freezePrep({ reason: 42 })).reason, null);
  assert.strictEqual(rp.buildScheduledPreparationDiagnostic(freezePrep({ reason: '' })).reason, null);
});

test('D6 stage is a closed enum; unknown or free-text stage maps to null, known stages pass', () => {
  assert.strictEqual(rp.buildScheduledPreparationDiagnostic(freezePrep({ stage: 'totally-made-up-stage' })).stage, null);
  assert.strictEqual(rp.buildScheduledPreparationDiagnostic(freezePrep({ stage: 'a-b'.repeat(20) })).stage, null);
  for (const s of ['driver-contract', 'state-recovery', 'creation-header', 'selection', 'selection-incomplete',
    'account-binding', 'account-rebinding', 'readiness', 'readiness-after-repair', 'plan-settings']) {
    assert.strictEqual(rp.buildScheduledPreparationDiagnostic(freezePrep({ stage: s })).stage, s);
  }
});

test('D7 settings diag whitelist carry-through is unchanged', () => {
  const packet = rp.buildScheduledPreparationDiagnostic(freezePrep({
    settingsDiag: {
      expected: { roi: 15, budget: 300, commissionChecked: true, optionalDirectPayChecked: false, planName: '创建计划2026-10-12_12:42' },
      observed: { roi: '15.00', budget: '300', commissionChecked: true, optionalDirectPayChecked: false, planName: '创建计划2026-10-12_12:42' },
    },
  }));
  assert.deepStrictEqual(packet.settings.expected, { roi: 15, budget: 300, commissionChecked: true, optionalDirectPayChecked: false, planName: '创建计划2026-10-12_12:42' });
  assert.deepStrictEqual(packet.settings.observed, { roi: '15.00', budget: '300', commissionChecked: true, optionalDirectPayChecked: false, planName: '创建计划2026-10-12_12:42' });
});

test('D8 the input prep object is never mutated', () => {
  const prep = freezePrep({ reason: 'sessionid=FAKE_SECRET', businessDate: '2026-10-12' });
  const before = JSON.parse(JSON.stringify(prep));
  rp.buildScheduledPreparationDiagnostic(prep);
  assert.deepStrictEqual(prep, before, 'public prep.reason and shape must stay verbatim');
});

// ── runner (synchronous assertions, no I/O) ──────────────────────────────────
(async () => {
  let failed = 0;
  for (const t of tests) {
    try { await t.fn(); process.stdout.write('ok  ' + t.name + '\n'); }
    catch (error) { failed++; process.stdout.write('FAIL ' + t.name + '\n     ' + (error && error.message) + '\n'); }
  }
  process.stdout.write('\n' + (tests.length - failed) + '/' + tests.length + ' passed\n');
  process.exit(failed ? 1 : 0);
})();
