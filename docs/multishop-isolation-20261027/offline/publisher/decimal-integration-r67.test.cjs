// ── A: decimal-canonical fill-skip + settings match through the REAL helper ──
test('A1 roi 15.00 / budget 300 succeeds with ZERO extra fills (decimal canonical, not Number)', async () => {
  const { page, calls, state } = makeFakePage({ roi: '15.00', budget: '300' });
  const result = await makeDriver(page).configurePlan({ businessDate: BUSINESS_DATE });
  assert.strictEqual(result.ok, true, JSON.stringify(result));
  assert.deepStrictEqual(calls.fills, [], 'equivalent 15.00/300 must not trigger any fill');
  assert.match(result.planName, new RegExp('^' + BUSINESS_DATE + '_千川乘方_\\d{2}:\\d{2}:\\d{2}$'), 'name generated by the real shanghaiPlanName path');
  assert.strictEqual(state.planName, result.planName);
  assert.deepStrictEqual(calls.nameWrites, [result.planName]);
  assert.strictEqual(calls.publishClicks, 0);
});

