function makeFakePage(stateOver) {
  const state = Object.assign({
    accountId: ACCOUNT, mainTableUnique: true,
    commissionChecked: true, optionalDirectPayChecked: false,
    roi: '15.00', budget: '300', planName: null,
    nameDrift: false,
  }, stateOver || {});
  const calls = { fills: [], commissionFix: 0, directPayFix: 0, guidance: 0, nameWrites: [], publishClicks: 0, observes: 0 };
  const page = {
    evaluate: async (fn, arg) => {
      if (fn === guard.pageObserve) {
        calls.observes++;
        return {
          observation: 'obs-' + calls.observes,
          creation: {
            accountId: state.accountId, mainTableUnique: state.mainTableUnique,
            roi: state.roi, budget: state.budget,
            commissionChecked: state.commissionChecked,
            optionalDirectPayChecked: state.optionalDirectPayChecked,
            planName: state.planName,
          },
          elements: [
            { index: 0, value: state.roi, fillField: { recognized: true, kind: 'roi' } },
            { index: 1, value: state.budget, fillField: { recognized: true, kind: 'budget' } },
          ],
        };
      }
      if (fn === rp.guidanceActionInPage) { calls.guidance++; return { present: false, unknown: null, roots: [] }; }
      if (fn === rp.ensureCommissionInPage) { calls.commissionFix++; return { fixed: true }; }
      if (fn === rp.ensureDirectPayOffInPage) { calls.directPayFix++; return { fixed: true }; }
      if (fn === rp.creationPlanNameInPage) {
        calls.nameWrites.push(arg);
        state.planName = state.nameDrift ? '创建计划2026-10-12_00:00' : arg;
        return { set: true };
      }
      if (fn === guard.actionApply) {
        if (arg && arg.op === 'publish-plan') { calls.publishClicks++; throw new Error('r67-fake-page-received-publish-click'); }
        calls.fills.push({ kind: arg.kind, value: arg.value, index: arg.index, observation: arg.observation });
        return { filled: true, field: arg.kind };
      }
      throw new Error('r67-unexpected-evaluate-target');
    },
  };
  return { page, state, calls };
}

function makeDriver(page, bizOver) {
  return rp.createRealDrivers({
    page, managerPage: page, context: {}, dayState: {}, persist: async () => {},
    publishedIds: new Set(), attemptedSet: new Set(), hints: {},
    accountId: ACCOUNT,
    business: Object.assign({ shop: 'R67TEST', accountId: ACCOUNT, roi: 15, dailyBudget: 300 }, bizOver || {}),
    boundAccounts: ['79863866', '9zmao_fushi'], productsPerPlan: 30,
    creationUrl: 'https://qianchuan.jinritemai.com/uni-creation/overall-product-multi?aavid=' + ACCOUNT,
    opened: {}, projectRoot: __dirname, planNumber: 1, runId: 'r67-offline',
    settingsReadbackSettleMs: 20,
  });
}

